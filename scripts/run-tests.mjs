// Runs the same measurement code as the browser over every file in test-set/ground-truth.csv
// and writes test-set/results.md. Ground truth is read ONLY to compute the error afterwards;
// it is never passed to measure().
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import sharp from 'sharp';
import { measure } from '../public/measure.js';
import { sizeFor } from '../public/sizing.js';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MAX_SIDE = 4096; // same cap as the browser

async function loadCv() {
  let cv = require('@techstark/opencv-js');
  if (cv instanceof Promise) cv = await cv;
  else if (!cv.Mat) await new Promise(r => { cv.onRuntimeInitialized = r; });
  return cv;
}

function parseCsv(text) {
  const [head, ...rows] = text.trim().split(/\r?\n/);
  const keys = head.split(',');
  return rows.filter(r => r.trim() && !r.startsWith('#')).map(r => Object.fromEntries(r.split(',').map((v, i) => [keys[i], v.trim()])));
}

const cv = await loadCv();
const truth = parseCsv(fs.readFileSync(path.join(root, 'test-set/ground-truth.csv'), 'utf8'));
const verbose = process.argv.includes('-v');
const lines = [];
let failures = 0;
for (const row of truth) {
  const file = path.join(root, 'test-set', row.file);
  if (!fs.existsSync(file)) { lines.push(`| ${row.file} | ${row.kind} | ${row.expected} | FILE MISSING | | | | | |`); failures++; continue; }
  const { data, info } = await sharp(file).rotate().resize(MAX_SIDE, MAX_SIDE, { fit: 'inside', withoutEnlargement: true }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const img = { data: new Uint8ClampedArray(data.buffer, data.byteOffset, data.length), width: info.width, height: info.height };
  // Optional: ruler reading of the check line on the sheet used for this photo (resized print).
  const opts = Number(row.sheet_line_mm) > 0 ? { printScale: Number(row.sheet_line_mm) / 100 } : {};
  measure(cv, img, opts); // warm-up so timing excludes one-off WASM/JIT cost
  let res = measure(cv, img, opts);
  const truths = row.true_inner_diameter_mm.split('|').map(Number);
  let actual = res.status, est = '', err = '', unc = '', within = '', size = '';
  const report = (r, t) => {
    const e = Math.abs(r.diameterMm - t);
    return { est: r.diameterMm.toFixed(2), err: e.toFixed(2), unc: '±' + r.uncertaintyMm.toFixed(2), within: e <= r.uncertaintyMm ? 'yes' : 'NO', size: 'ISO ' + sizeFor(r.diameterMm, r.uncertaintyMm).iso.label };
  };
  if (res.status === 'ok') ({ est, err, unc, within, size } = report(res, truths[0]));
  else if (res.status === 'retake') actual = 'retake: ' + res.reasons.map(r => r.code).join('+');
  else if (res.status === 'choose') {
    // exercise the confirmation path: select each candidate in turn
    const parts = res.overlay.candidates.map((_, i) => {
      const r = measure(cv, img, { ...opts, select: i });
      if (r.status !== 'ok') return { est: r.status, err: '-', unc: '', within: '', size: '' };
      const t = truths.reduce((a, b) => Math.abs(b - r.diameterMm) < Math.abs(a - r.diameterMm) ? b : a);
      return report(r, t);
    });
    est = parts.map(p => p.est).join(' / '); err = parts.map(p => p.err).join(' / ');
    unc = parts.map(p => p.unc).join(' / '); within = parts.map(p => p.within).join(' / '); size = parts.map(p => p.size).join(' / ');
    actual = `choose (${parts.length} rings)`;
  }
  const want = row.expected === 'retake' ? `retake: ${row.expected_reason}` : row.expected;
  const pass = row.expected === 'measure' ? res.status === 'ok' : row.expected === 'choose' ? res.status === 'choose' : actual === want;
  if (!pass) failures++;
  lines.push(`| ${row.file.split('/').pop()} | ${row.kind} | ${want} | ${actual} | ${row.expected === 'retake' ? '-' : row.true_inner_diameter_mm.replace('|', ' / ')} | ${est} | ${err} | ${unc} | ${within} | ${size} | ${res.timingMs.total.toFixed(0)} | ${pass ? 'pass' : 'FAIL'} |`);
  if (verbose) console.log(row.file, JSON.stringify({ checks: res.checks, timing: res.timingMs, u: res.uncertaintyTerms }, (k, v) => typeof v === 'number' ? +v.toFixed(3) : (k === 'edgePoints' ? undefined : v)));
}
const header = [
  '| Photo | Kind | Expected | Actual | True inner Ø (mm) | Estimated Ø (mm) | Absolute error (mm) | Stated uncertainty | Error within uncertainty | Size | Time (ms, Node) | Outcome |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|',
];
const out = ['# Test results', '', `Generated by \`npm test\` on ${new Date().toISOString().slice(0, 10)}. Times are from Node on the build machine, not a phone.`, '', ...header, ...lines, ''].join('\n');
fs.writeFileSync(path.join(root, 'test-set/results.md'), out);
console.log(out);
process.exit(failures ? 1 : 0);
