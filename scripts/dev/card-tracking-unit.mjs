import assert from 'node:assert/strict';
import {canCaptureCard, CARD_TRACK_MAX_AGE_MS, enableContinuousFocus, trackCardFrame} from '../../public/card-camera.js';
const card = [[120,280],[410,280],[410,462],[120,462]], ring = [[455,400],[460,410],[455,420],[445,410]];
const offset = (q,x,step=0)=>q.map((_,i)=>{const [a,b]=q[(i+step)%q.length];return [a+x,b];});
const observed=(x=0,step=0,alter={})=>({status:'preview',overlay:{card:offset(card,x,step),inner:offset(ring,x,step)},guideDiameterMm:18,checks:{pxPerMm:3.4},...alter});
const tick=(p,r,time,frameTime=time,width=720,height=1280)=>trackCardFrame(p,r,{time,frameTime,width,height});
const empty=tick(null,{status:'retake',overlay:{}},0);
assert.equal(empty.state,'unconfirmed');
assert.deepEqual(empty.ringDraw,[]);
let weak=empty;
for(const time of [100,300,500,700])weak=tick(weak,{status:'retake',overlay:{cardHint:card,inner:ring}},time);
assert.equal(weak.state,'card-hint');
assert.deepEqual(weak.cardDraw,card);
assert.deepEqual(weak.ringDraw,[]);
assert.equal(canCaptureCard(weak,700),false,'possible reference never opens the shutter');
const only=tick(empty,{status:'retake',overlay:{card}},100);
assert.equal(only.state,'card-only');
assert.deepEqual(only.cardDraw,card);
assert.deepEqual(only.ringDraw,[]);
assert.equal(canCaptureCard(only,100),false);
let p=tick(only,observed(),200);
assert.equal(p.state,'both');
assert.equal(canCaptureCard(p,200),false);
assert.equal(tick(p,observed(),260,200),p,'same video frame cannot count twice');
p=tick(p,observed(2,1),360);
assert.equal(p.stable,2);
assert.equal(p.cardDraw[0][0],121.5,'display eased, raw points used for gate');
p=tick(p,observed(3,2),560);
assert.equal(p.card[0][0],123,'cyclic contour starting point does not break tracking');
assert.equal(canCaptureCard(p,560),true);
const bridged=tick(p,observed(3,0,{checks:{pxPerMm:3.4,edgeBridge:true}}),700);
assert.equal(bridged.stable,1);
assert.equal(canCaptureCard(bridged,700),false,'switching to an inferred edge resets stability');
assert.equal(canCaptureCard(p,560+CARD_TRACK_MAX_AGE_MS),false);
assert.equal(canCaptureCard(tick(p,observed(80),700),700),false,'jump resets stability');
assert.equal(canCaptureCard(tick(p,observed(),700,700,1280,720),700),false,'orientation/format change resets stability');
const partial=tick(p,{status:'retake',overlay:{card}},700);
assert.deepEqual(partial.ringDraw,[]);
assert.equal(canCaptureCard(partial,700),false);
const detectedButRejected=tick(p,observed(0,0,{status:'retake'}),700);
assert.equal(detectedButRejected.state,'both');
assert.equal(canCaptureCard(detectedButRejected,700),false);
assert.equal(tick(p,observed(),1700).stable,1,'an evidence gap resets stability');
assert.deepEqual(tick(p,{status:'retake',overlay:{}},710).cardDraw,[]);
let calls=[];
assert.equal(await enableContinuousFocus({getCapabilities:()=>({focusMode:['continuous','manual']}),getSettings:()=>({focusMode:'manual'}),
  applyConstraints:async c=>calls.push(c)}),true);
assert.deepEqual(calls,[{advanced:[{focusMode:'continuous'}]}]);
assert.equal(await enableContinuousFocus({}),false);
assert.equal(await enableContinuousFocus({getCapabilities:()=>({focusMode:['continuous']}),getSettings:()=>({focusMode:'continuous'})}),false);
assert.equal(await enableContinuousFocus({getCapabilities:()=>({focusMode:['continuous']}),applyConstraints:async()=>{throw Error('rejected');}}),false);
console.log('PASS actual-only animated paths, partial/ambiguous detection, stale/duplicate/rotated frame capture gating, and hardware focus capability checks.');
