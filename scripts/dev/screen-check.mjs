import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { CARD_WIDTH_MM, CARD_SHORT_MM, circlePixels } from '../../public/screen-sizing.js';

assert.equal(CARD_WIDTH_MM, 85.60);
assert.equal(circlePixels(20, 428), 100);

const files = new URL('../../public/', import.meta.url);
const mime = { js: 'text/javascript', css: 'text/css', jpg: 'image/jpeg', html: 'text/html' };
const server = createServer(async (req, res) => {
  try {
    const pathname = new URL(req.url, 'http://localhost').pathname.replace(/^\/+/, '') || 'index.html';
    const contents = await readFile(new URL(pathname, files));
    res.writeHead(200, { 'Content-Type': mime[pathname.split('.').pop()] || 'application/octet-stream' });
    res.end(contents);
  } catch { res.writeHead(404).end(); }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const url = `http://127.0.0.1:${server.address().port}`;
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, screen: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const runtimeErrors = [];
  phone.on('pageerror', error => runtimeErrors.push(error.message));
  // Test screen mode even with the photo engine unavailable.
  await phone.route('**/vendor/opencv.js', route => route.abort());
  await phone.goto(url);
  assert.equal(await phone.locator('#start').isVisible(), true);
  assert.equal(await phone.locator('#screen').isVisible(), false);
  await phone.getByRole('link', { name: /No-printer measurement/ }).click();
  assert.equal(await phone.locator('#start').isVisible(), false);
  assert.equal(await phone.locator('#screen-fit').isVisible(), false);
  await phone.getByRole('button', { name: 'Calibrate with a card' }).click();
  assert.equal(await phone.getByRole('radio', { name: 'Upright card (short edge)' }).isChecked(), true);
  const line = await phone.locator('#cal-line').boundingBox();
  assert.equal(line.width, 204);
  const card = await phone.locator('#cal-card-shape').boundingBox();
  assert.equal(card.x, line.x);
  assert.equal(card.width, line.width);
  assert.ok(card.height > card.width);
  await phone.getByRole('button', { name: 'Make the guide longer (small step)' }).click();
  const nudged = await phone.locator('#cal-line').boundingBox();
  assert.equal(nudged.x, line.x);
  assert.equal(nudged.width, 205);
  await phone.locator('#cal-stage').hover();
  await phone.mouse.wheel(0, 200);
  assert.deepEqual(await phone.locator('#cal-line').boundingBox(), nudged);
  await phone.getByRole('button', { name: 'Both card edges line up' }).click();
  assert.equal(await phone.locator('#screen-fit').isVisible(), true);
  await phone.waitForFunction(() => document.activeElement?.id === 'ring-fit-title' && document.querySelector('#ring-dialog').open);
  assert.ok(await phone.locator('html').evaluate(el => el.classList.contains('calibration-open')));
  assert.ok(await phone.locator('#ring-fit-title').evaluate(el => el.getBoundingClientRect().top >= 0 && el.getBoundingClientRect().bottom <= innerHeight));
  await phone.locator('#screen-diameter').fill('20');
  const circle = await phone.locator('#screen-circle').boundingBox();
  assert.ok(Math.abs(circle.width - circlePixels(20, 205, CARD_SHORT_MM)) < .02);
  assert.equal(circle.width, circle.height);
  await phone.locator('#ring-stage').hover();
  await phone.mouse.wheel(0, 300);
  assert.deepEqual(await phone.locator('#screen-circle').boundingBox(), circle);
  await phone.locator('#ring-stage').click();
  assert.equal(await phone.locator('#ring-dialog').isVisible(), true);
  const shielded = await phone.locator('#ring-stage').evaluate(stage => {
    return ['touchstart', 'touchmove', 'touchend', 'click', 'dblclick', 'contextmenu', 'dragstart'].every(type => {
      const e = new Event(type, { bubbles: true, cancelable: true });
      Object.defineProperty(e, 'touches', { value: [1, 2] });
      stage.dispatchEvent(e);
      return e.defaultPrevented;
    });
  });
  assert.equal(shielded, true);
  await phone.getByRole('button', { name: 'The circle fits' }).click();
  assert.match(await phone.locator('#screen-reading').textContent(), /20\.0 mm · ISO 63/);
  await phone.getByRole('button', { name: 'Make ring circle larger' }).click();
  assert.equal(await phone.locator('#screen-reading').textContent(), '');
  const adjusted = await phone.locator('#screen-circle').boundingBox();
  assert.ok(Math.abs((adjusted.x + adjusted.width / 2) - (circle.x + circle.width / 2)) < .02);
  assert.ok(Math.abs((adjusted.y + adjusted.height / 2) - (circle.y + circle.height / 2)) < .02);
  await phone.getByRole('button', { name: 'The circle fits' }).click();
  await phone.reload();
  await phone.locator('#ring-dialog').waitFor({ state: 'visible' });
  assert.equal(await phone.locator('#screen-diameter').inputValue(), '20.1');
  assert.match(await phone.locator('#screen-reading').textContent(), /20\.1 mm/);
  await phone.getByRole('button', { name: 'Done' }).click();
  await phone.locator('#ring-dialog').waitFor({ state: 'hidden' });
  assert.match(await phone.locator('#screen-last-reading').textContent(), /20\.1 mm/);
  await phone.reload();
  assert.equal(await phone.locator('#screen-fit').isVisible(), true);
  assert.match(await phone.locator('#cal-status').textContent(), /Saved calibration restored/);
  assert.equal(await phone.locator('#ring-dialog').isVisible(), false);
  await phone.getByRole('button', { name: 'Measure ring', exact: true }).click();
  await phone.getByRole('button', { name: 'Exit fitting' }).click();
  await phone.setViewportSize({ width: 820, height: 390 });
  assert.equal(await phone.locator('#screen-fit').isVisible(), true);
  await phone.getByRole('button', { name: 'Recalibrate with a card' }).click();
  await phone.keyboard.press('Escape');
  await phone.locator('#cal-dialog').waitFor({ state: 'hidden' });
  const landscape = await browser.newPage({ viewport: { width: 568, height: 300 } });
  await landscape.goto(url + '/#screen');
  await landscape.getByRole('button', { name: 'Calibrate with a card' }).click();
  await landscape.getByRole('radio', { name: 'Upright card (short edge)' }).check();
  await landscape.getByRole('button', { name: 'Make the guide shorter (large step)' }).click();
  await landscape.getByRole('button', { name: 'Both card edges line up' }).click();
  assert.equal(await landscape.locator('#screen-fit').isVisible(), true);
  await landscape.locator('#ring-dialog').waitFor({ state: 'visible' });
  await landscape.getByRole('button', { name: 'Make ring circle larger' }).click();
  await landscape.getByRole('button', { name: 'Exit fitting' }).click();
  const desktop = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  await desktop.goto(url + '/#screen');
  await desktop.getByRole('button', { name: 'Calibrate with a card' }).click();
  assert.equal(await desktop.getByRole('radio', { name: 'Sideways card (long edge)' }).isChecked(), true);
  assert.equal((await desktop.locator('#cal-line').boundingBox()).width, 324);
  const landscapeCard = await desktop.locator('#cal-card-shape').boundingBox();
  assert.ok(landscapeCard.width > landscapeCard.height);
  await desktop.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await desktop.locator('.cal-card-cue').evaluate(el => getComputedStyle(el).animationName), 'none');
  assert.deepEqual(runtimeErrors, []);

  const photo = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await photo.goto(url);
  assert.ok(await photo.locator('#start').evaluate((section) => Boolean(section.compareDocumentPosition(document.querySelector('#screen')) & Node.DOCUMENT_POSITION_FOLLOWING)));
  await photo.getByRole('link', { name: /No-printer measurement/ }).click();
  assert.equal(new URL(photo.url()).hash, '#screen');
  await photo.getByRole('link', { name: /Photo measurement/ }).click();
  assert.equal(new URL(photo.url()).hash, '#start');
  await photo.getByRole('link', { name: 'More samples' }).click();
  assert.equal(new URL(photo.url()).hash, '#samples');
  await photo.getByRole('button', { name: 'Try a sample photo' }).click();
  await photo.waitForFunction(() => window.__lastResult?.status === 'ok', null, { timeout: 30000 });
  assert.ok(Math.abs(await photo.evaluate(() => window.__lastResult.diameterMm) - 18.80) < .15);
  assert.equal(await photo.locator('#screen').isVisible(), false);
  await photo.getByRole('button', { name: 'Start over' }).click();
  assert.equal(await photo.locator('#start').isVisible(), true);
  assert.equal(await photo.locator('#screen').isVisible(), false);
  console.log('PASS: calibration geometry, match/size, nudge, viewport reset, recalibration and no-print sample photo.');
} finally {
  if (browser) await browser.close();
  server.close();
}
